import Cocoa
import Carbon.HIToolbox
import ApplicationServices

final class PasteService {
    enum Outcome {
        case pasted
        /// No Accessibility permission: text is on the clipboard for a manual ⌘V.
        case copiedOnly
    }

    private let pasteboard = NSPasteboard.general
    // Marks our temporary clipboard write so clipboard managers skip it (nspasteboard.org).
    private let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private var pendingRestore: DispatchWorkItem?
    private var savedItems: [NSPasteboardItem]?

    func paste(_ text: String, trace: LatencyTrace? = nil) -> Outcome {
        trace?.mark("paste.started")
        guard AXIsProcessTrusted() else {
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
            return .copiedOnly
        }

        trace?.mark("paste.permissionChecked")

        // If a restore is still pending from a previous paste, keep the original clipboard.
        pendingRestore?.cancel()
        let original = savedItems ?? snapshot()
        savedItems = original
        trace?.mark("paste.clipboardSnapshotted")

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setString("", forType: transientType)
        item.setString("", forType: autoGeneratedType)
        pasteboard.writeObjects([item])
        let ourChangeCount = pasteboard.changeCount

        trace?.mark("paste.clipboardWritten")
        postCommandV()
        trace?.mark("paste.eventsPosted")

        // Give slow apps (Electron, browsers) time to read the clipboard before restoring it.
        let restore = DispatchWorkItem { [weak self] in
            guard let self else { return }
            defer { self.savedItems = nil }
            // Don't clobber something the user copied in the meantime.
            guard self.pasteboard.changeCount == ourChangeCount else { return }
            self.pasteboard.clearContents()
            if !original.isEmpty { self.pasteboard.writeObjects(original) }
        }
        pendingRestore = restore
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.6, execute: restore)
        return .pasted
    }

    private func snapshot() -> [NSPasteboardItem] {
        (pasteboard.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) {
                    copy.setData(data, forType: type)
                }
            }
            return copy
        }
    }

    private func postCommandV() {
        let source = CGEventSource(stateID: .hidSystemState)
        let keyDown = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true)
        let keyUp = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false)
        keyDown?.flags = .maskCommand
        keyUp?.flags = .maskCommand
        keyDown?.post(tap: .cghidEventTap)
        keyUp?.post(tap: .cghidEventTap)
    }
}
